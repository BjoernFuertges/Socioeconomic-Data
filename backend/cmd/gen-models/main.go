func snakeToCamel(s string) string {
	parts := strings.Split(s, "_")
	var b strings.Builder
	for _, p := range parts {
		if len(p) == 0 {
			continue
		}
		r := []rune(p)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

func modelSlug(modelName string) string {
	// Remove stg_ prefix
	slug := strings.TrimPrefix(modelName, "stg_")
	// Remove geographic level suffixes: _kreise, _gemeinden, _nuts3, etc.
	for _, suffix := range []string{"_kreise", "_gemeinden", "_nuts3", "_lau"} {
		slug = strings.TrimSuffix(slug, suffix)
	}
	return slug
}

func getLevelSuffix(modelName string) string {
	// Extract geographic level suffix from model name
	// Returns "_kreise", "_gemeinden", "_nuts3", etc. or empty string
	name := strings.TrimPrefix(modelName, "stg_")
	for _, suffix := range []string{"_kreise", "_gemeinden", "_nuts3", "_lau"} {
		if strings.HasSuffix(name, suffix) {
			return suffix
		}
	}
	return ""
}

func dbtTypeToGo(dt string) string {
	switch strings.ToLower(dt) {
	case "integer", "bigint", "smallint", "int":
		return "int"
	case "numeric", "decimal", "real", "double precision", "float":
		return "float64"
	case "boolean", "bool":
		return "bool"
	default:
		return "string"
	}
}

func exampleForType(goType string, ar *acceptedRange) string {
	switch goType {
	case "int":
		if ar != nil && ar.MinValue != nil {
			return strconv.Itoa(int(*ar.MinValue))
		}
		return "0"
	case "float64":
		if ar != nil && ar.MaxValue != nil && ar.MinValue != nil && *ar.MinValue == 0 {
			return fmt.Sprintf("%.2f", *ar.MaxValue/2.0)
		}
		if ar != nil && ar.MinValue != nil && *ar.MinValue > 0 {
			return fmt.Sprintf("%.2f", *ar.MinValue)
		}
		return "0"
	case "bool":
		return "true"
	default:
		return ""
	}
}

func parseAcceptedRange(node yaml.Node) *acceptedRange {
	if node.Kind == 0 {
		return nil
	}
	ar := &acceptedRange{}
	found := false
	var walk func(n *yaml.Node)
	walk = func(n *yaml.Node) {
		if n.Kind == yaml.MappingNode {
			for i := 0; i+1 < len(n.Content); i += 2 {
				key := n.Content[i].Value
				val := n.Content[i+1]
				switch key {
				case "min_value":
					if f, err := strconv.ParseFloat(val.Value, 64); err == nil {
						ar.MinValue = &f
						found = true
					}
				case "max_value":
					if f, err := strconv.ParseFloat(val.Value, 64); err == nil {
						ar.MaxValue = &f
						found = true
					}
				}
				walk(val)
			}
		}
		for _, child := range n.Content {
			walk(child)
		}
	}
	walk(&node)
	if !found {
		return nil
	}
	return ar
}

func buildDataset(m dbtModel) dataset {
	slug := modelSlug(m.Name)
	level := getLevelSuffix(m.Name)

	title := snakeToCamel(slug)
	routeSlug := slug

	// Keep historical route/title style for *_kreise models (e.g. /bevoelkerung).
	// Add suffix only for alternative levels to avoid naming collisions
	// (e.g. beschaeftigungsquote-gemeinden, beschaeftigungsquote-nuts3).
	if level != "" && level != "_kreise" {
		levelCamel := snakeToCamel(strings.TrimPrefix(level, "_"))
		title = title + levelCamel
		routeSlug = slug + strings.ReplaceAll(level, "_", "-")
	}

	ds := dataset{
		ModelName:             m.Name,
		Description:           m.Description,
		StructName:            title + "Data",
		ConfigVar:             title + "Config",
		HandlerFunc:           "Get" + title + "Data",
		TimeseriesHandlerFunc: "Get" + title + "TimeseriesData",
		RouteSlug:             routeSlug,
		Tag:                   title,
		DBSchema:              "transformed_data",
		DBTable:               m.Name,
		IsHarmonized:          harmonizedRouteSlugs[routeSlug],
		IsHarmonizedLau:       harmonizedLauRouteSlugs[routeSlug],
	}
	for _, col := range m.Columns {
		if col.Name == "year" {
			ds.YearRange = parseAcceptedRange(col.Tests)
			break
		}
	}
	for _, col := range m.Columns {
		if strings.HasSuffix(col.Name, "_pk") || baseColumnSet[col.Name] {
			continue
		}
		ar := parseAcceptedRange(col.Tests)
		gt := dbtTypeToGo(col.DataType)
		ds.ValueFields = append(ds.ValueFields, valueField{
			GoName:  snakeToCamel(col.Name),
			DBCol:   col.Name,
			JSONKey: col.Name,
			GoType:  gt,
			Desc:    col.Description,
			Example: exampleForType(gt, ar),
		})
	}
	// LAU fill-gaps views can carry extra flag columns (render_lau_fill_gaps_view
	// flag_columns); NUTS-3 views only have the single value column.
	if ds.IsHarmonizedLau || (ds.IsHarmonized && len(ds.ValueFields) == 1) {
		ds.InterpolatedTable = "api_" + strings.ReplaceAll(routeSlug, "-", "_") + "_fill_gaps"
	}
	return ds
}

func renderTemplate(name, tpl string, data interface{}) []byte {
	t := template.Must(template.New(name).Parse(tpl))
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		log.Fatalf("template %s: %v", name, err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "--- unformatted (%s) ---\n%s\n---\n", name, buf.String())
		log.Fatalf("gofmt %s: %v", name, err)
	}
	return src
}

func main() {
	cwd, err := os.Getwd()
	if err != nil {
		log.Fatal(err)
	}
	projectRoot := filepath.Join(cwd, "..", "..", "..")
	stagingDir := filepath.Join(projectRoot, "pipeline", "dbt", "socioeconomic_data_pipeline", "models", "staging")

	// Match only geographic soziodata staging schemas.
	// This keeps historical behaviour for *_kreise and adds *_gemeinden / *_nuts3.
	patterns := []string{
		"stg_*_kreise_schema.yml",
		"stg_*_gemeinden_schema.yml",
		"stg_*_nuts3_schema.yml",
		"stg_*_lau_schema.yml",
	}

	var matches []string
	for _, pattern := range patterns {
		found, globErr := filepath.Glob(filepath.Join(stagingDir, pattern))
		if globErr != nil {
			log.Fatalf("glob error for pattern %s: %v", pattern, globErr)
		}
		matches = append(matches, found...)
	}

	if len(matches) == 0 {
		log.Fatalf("no schema files found in %s", stagingDir)
	}
	sort.Strings(matches)
	uniq := make([]string, 0, len(matches))
	for i, m := range matches {
		if i == 0 || m != matches[i-1] {
			uniq = append(uniq, m)
		}
	}
	matches = uniq
	var datasets []dataset
	for _, path := range matches {
		raw, err := os.ReadFile(path)
		if err != nil {
			log.Fatalf("read %s: %v", path, err)
		}
		var schema dbtSchema
		if err := yaml.Unmarshal(raw, &schema); err != nil {
			log.Fatalf("parse %s: %v", path, err)
		}
		for _, model := range schema.Models {
			if !(strings.HasSuffix(model.Name, "_kreise") ||
				strings.HasSuffix(model.Name, "_gemeinden") ||
				strings.HasSuffix(model.Name, "_nuts3") ||
				strings.HasSuffix(model.Name, "_lau")) {
				continue
			}
			datasets = append(datasets, buildDataset(model))
		}
	}
	if len(datasets) == 0 {
		log.Fatal("no models parsed from schema files")
	}
	outModels := filepath.Join(cwd, "models_soziodata_generated.go")
	outHandlers := filepath.Join(cwd, "..", "handlers", "handlers_soziodata_generated.go")
	outRoutes := filepath.Join(cwd, "..", "routes", "routes_soziodata_generated.go")
	if err := os.WriteFile(outModels, renderTemplate("models", modelsTpl, datasets), 0644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %s\n", outModels)
	if err := os.WriteFile(outHandlers, renderTemplate("handlers", handlersTpl, datasets), 0644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %s\n", outHandlers)
	if err := os.WriteFile(outRoutes, renderTemplate("routes", routesTpl, datasets), 0644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %s\n", outRoutes)
}
