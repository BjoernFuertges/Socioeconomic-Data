func (ds dataset) YearRangeStr() string {
	if ds.YearRange == nil {
		return ""
	}
	var parts []string
	if ds.YearRange.MinValue != nil {
		parts = append(parts, strconv.Itoa(int(*ds.YearRange.MinValue)))
	}
	if ds.YearRange.MaxValue != nil {
		parts = append(parts, strconv.Itoa(int(*ds.YearRange.MaxValue)))
	}
	return strings.Join(parts, "-")
}

